/**
 * A/B-1 for nexttask 10 — does the env-template closure check add the mx5 run-19
 * finding to the final gate's ranked failure list without changing the verdict of
 * anything else?
 *
 * Deterministic: no model, no PI_BIN, no llama-server, no network. Both arms are
 * the REAL `runFinalIntegrationGate` — the baseline is the module as shipped at
 * BASELINE_REF, extracted with `git show` into a sibling file so its relative
 * imports still resolve; the treatment is the working tree. BASELINE_REF is
 * PINNED, not `HEAD`: once the lever lands, `HEAD` contains it and a re-run would
 * compare the lever against itself and report a triumphant zero.
 *
 * The gate RUNS COMMANDS and its statics WRITE (`prettier --write`, `eslint
 * --fix`), so every tree is materialised into a throwaway clone per ARM — the two
 * arms never share a tree, and the corpus is never touched. The docker shim from
 * the boot-skip harness is reused so a `dev` script that starts containers cannot
 * start anything on this box.
 *
 * Pre-registered metric: the gate VERDICT and its RANKED FAILURE LIST per tree.
 *
 *     PASS      mx5@dfbdd6f gains a rank-0 failure naming ADMIN_PHONE and
 *               ADMIN_PASSWORD with their read sites, AND every invariant
 *               holds.                                                    exit 0
 *     FAIL      it does not, or any invariant breaks.                     exit 1
 *     ABSTAIN   no tree in the corpus carries a template.                 exit 2
 *
 * Invariants (nexttask 10, verbatim):
 *   inv-no-template-no-finding    a tree with no tracked env template is
 *                                 byte-identical to baseline (ENOENT = pass).
 *   inv-declared-silent           a DECLARED variable never produces a finding,
 *                                 however it is read. The check is one-directional.
 *   inv-untracked-invisible       reads in untracked/gitignored files produce
 *                                 nothing — and an untracked template declares
 *                                 nothing.
 *   inv-no-verdict-flip-on-clean  a tree that PASSes baseline with no missing var
 *                                 still PASSes. dace-pro is the fixture.
 *   inv-idempotent                scanning twice yields the same findings.
 *
 * A difference between arms that is NOT an env-closure line is reported as
 * SUITE FLAKE, loudly, and breaks the identity invariants — two clones of one
 * tree running the same commands should produce the same list, and if they do
 * not, this harness must say so rather than average it away.
 *
 *     bun run scripts/env-template-closure-ab.ts
 */
import {spawnSync} from 'node:child_process'
import {mkdirSync, rmSync, writeFileSync} from 'node:fs'
import * as path from 'node:path'
import type {FinalGateOutcome, FinalGateOptions} from '../src/task/final-gate.js'
import {scanEnvTemplateClosure} from '../src/task/env-template-closure.js'
import {report, type Invariant, type Outcome} from './ab-verdict.js'
import {HUB, REPO, makeWorkRoot, installDockerlessShim} from './boot-skip-corpus.js'

const BASELINE_REF = process.env.ENV_CLOSURE_BASELINE_REF ?? '54ed4ad'
const BASELINE_FILE = path.join(REPO, 'src', 'task', 'final-gate.baseline.gen.ts')
/** Every gate command gets the same ceiling in both arms, so it can shift a
 *  tree's verdict but never the DIFFERENCE the A/B measures. */
const GATE_TIMEOUT_MS = 600_000

type GateFn = (cwd: string, opts?: FinalGateOptions) => Promise<FinalGateOutcome>

async function loadBaselineGate(): Promise<GateFn> {
    const show = spawnSync('git', ['show', `${BASELINE_REF}:src/task/final-gate.ts`], {
        cwd: REPO,
        encoding: 'utf8',
        maxBuffer: 32 * 1024 * 1024
    })
    if (show.status !== 0 || !show.stdout) {
        throw new Error(`cannot read final-gate.ts at ${BASELINE_REF}: ${show.stderr}`)
    }
    writeFileSync(
        BASELINE_FILE,
        `// GENERATED by scripts/env-template-closure-ab.ts from ${BASELINE_REF} — do not edit, do not commit.\n`
            + show.stdout
    )
    try {
        const mod = (await import(BASELINE_FILE)) as {runFinalIntegrationGate: GateFn}
        return mod.runFinalIntegrationGate
    } finally {
        rmSync(BASELINE_FILE, {force: true})
    }
}

// ── corpus ────────────────────────────────────────────────────────────────────

interface Tree {
    label: string
    /** Materialise the tree at `dest`. Runs once per ARM. */
    build: (dest: string) => void
    /** Variables the treatment is EXPECTED to name, in order. */
    expect: string[]
    /** What this tree is here to prove. */
    note: string
    lead?: true
    /** Per-tree ceiling; suites that are LLM/network harnesses get a short one. */
    timeoutMs?: number
}

function gitInit(dir: string): void {
    spawnSync('git', ['init', '-q'], {cwd: dir})
    spawnSync('git', ['add', '-A'], {cwd: dir})
    spawnSync('git', ['-c', 'user.email=a@b', '-c', 'user.name=a', 'commit', '-qm', 'fixture'], {
        cwd: dir
    })
}

function writeFiles(dir: string, files: Record<string, string>): void {
    for (const [rel, body] of Object.entries(files)) {
        mkdirSync(path.dirname(path.join(dir, rel)), {recursive: true})
        writeFileSync(path.join(dir, rel), body)
    }
}

/** A clone of a real tree (CoW where the filesystem allows). */
function clone(source: string, dest: string, after?: (dest: string) => void): void {
    rmSync(dest, {recursive: true, force: true})
    mkdirSync(path.dirname(dest), {recursive: true})
    const cp = spawnSync('cp', ['-a', '--reflink=auto', source, dest], {encoding: 'utf8'})
    if (cp.status !== 0) throw new Error(`cp failed for ${source}: ${cp.stderr}`)
    after?.(dest)
}

