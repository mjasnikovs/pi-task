// ── run ───────────────────────────────────────────────────────────────────────

const ENV_LINE_RE = /^env closure: /

/**
 * Failure texts quote command output, and that output carries two things that
 * cannot be equal across two clones: the tree's ABSOLUTE PATH (each arm gets its
 * own) and the suite's own ELAPSED TIME (`[90.00ms]` vs `[97.00ms]`). The first
 * run of this harness reported three identical failures as appeared/disappeared
 * for the path alone, and the second still differed on the milliseconds. Both are
 * normalised out — the full path, its basename (failure text is tail-truncated,
 * so a fragment can start mid-path), and any duration literal. Nothing else is
 * rewritten: a real difference in what failed still shows.
 */
function normalise(dest: string, s: string): string {
    return s
        .split(dest)
        .join('<TREE>')
        .split(path.basename(dest))
        .join('<TREE>')
        .replace(/\[\d+(?:\.\d+)?\s*m?s\]/g, '[<T>]')
        .replace(/\b\d+(?:\.\d+)?\s*ms\b/g, '<T>ms')
}

const listOf = (o: FinalGateOutcome): string[] => o.failures ?? (o.ok ? [] : [o.reason])

interface ArmResult {
    ok: boolean
    failures: string[]
}

/**
 * ONE snapshot per tree, copied into each arm — never two independent
 * materialisations. The second run of this harness cloned `pi-task (self)` for
 * the baseline arm, ran it, and cloned again for the treatment arm minutes
 * later, by which time the source tree (this repo, under active edit) had gained
 * a file that did not typecheck: the treatment "grew" a lint failure the lever
 * had nothing to do with. A live tree drifts; the A/B must not sample it twice.
 */
function snapshotOf(tree: Tree, work: string): string {
    const snap = path.join(work, `${slug(tree.label)}-snapshot`)
    tree.build(snap)
    return snap
}

async function runArm(gate: GateFn, snap: string, tree: Tree, dest: string): Promise<ArmResult> {
    rmSync(dest, {recursive: true, force: true})
    const cp = spawnSync('cp', ['-a', '--reflink=auto', `${snap}/.`, dest], {encoding: 'utf8'})
    if (cp.status !== 0) throw new Error(`cp of snapshot failed for ${tree.label}: ${cp.stderr}`)
    const o = await gate(dest, {timeoutMs: tree.timeoutMs ?? GATE_TIMEOUT_MS})
    return {ok: o.ok, failures: listOf(o).map(f => normalise(dest, f))}
}

async function main(): Promise<void> {
    const t0 = Date.now()
    const baselineGate = await loadBaselineGate()
    const {runFinalIntegrationGate: treatmentGate} = await import('../src/task/final-gate.js')
    const work = makeWorkRoot('env-closure-ab')
    installDockerlessShim(work)

    const rows: string[] = []
    const flakes: string[] = []
    let leadPass = false
    let templatesSeen = 0
    let declaredSilent = true
    let untrackedInvisible = true
    let noTemplateIdentical = true
    let noFlipOnClean = true
    let idempotent = true

    for (const tree of CORPUS) {
        const snap = snapshotOf(tree, work)
        // EQUAL-LENGTH arm directories. Failure text is tail-truncated by the gate
        // (last ~300 chars), so a longer directory name shifts the truncation
        // window: with `-baseline`/`-treatment` the two arms' quoted output began
        // one character apart and stayed unequal even after the path itself was
        // normalised away. Same length ⇒ same window ⇒ a difference means a
        // difference.
        const base = path.join(work, `${slug(tree.label)}-arm-a`)
        const treat = path.join(work, `${slug(tree.label)}-arm-b`)
        const b = await runArm(baselineGate, snap, tree, base)
        const t = await runArm(treatmentGate, snap, tree, treat)
        rmSync(snap, {recursive: true, force: true})
        const closure = scanEnvTemplateClosure(treat)
        if (closure.templates.length > 0) templatesSeen++
        // Idempotence on the tree the treatment actually saw.
        const again = scanEnvTemplateClosure(treat)
        const key = (c: typeof closure): string =>
            c.missing.map(m => `${m.name}@${m.file}:${m.line}`).join('|')
        if (key(closure) !== key(again)) idempotent = false

        const added = t.failures.filter(f => !b.failures.includes(f))
        const removed = b.failures.filter(f => !t.failures.includes(f))
        const envAdded = added.filter(f => ENV_LINE_RE.test(f))
        const otherAdded = added.filter(f => !ENV_LINE_RE.test(f))
        if (otherAdded.length > 0 || removed.length > 0) {
            flakes.push(
                `${tree.label}: ${otherAdded.length} non-env line(s) appeared, ${removed.length} disappeared`
                    + `\n    + ${otherAdded.join('\n    + ')}${removed.length ? `\n    - ${removed.join('\n    - ')}` : ''}`
            )
        }
        const namesFound = tree.expect.filter(n => envAdded.some(f => f.includes(n)))
        const rankZeroFirst = t.failures.length <= 1 || ENV_LINE_RE.test(t.failures[0]) || envAdded.length === 0

        rows.push(
            `${tree.label}\n`
                + `    ${tree.note}\n`
                + `    baseline  ${b.ok ? 'PASS' : 'FAIL'} (${b.failures.length} failures)\n`
                + `    treatment ${t.ok ? 'PASS' : 'FAIL'} (${t.failures.length} failures)\n`
                + `    env findings added: ${envAdded.length}`
                + (envAdded.length > 0 ? `\n      ${envAdded.join('\n      ')}` : '')
        )

        if (tree.lead) {
            leadPass =
                namesFound.length === tree.expect.length
                && envAdded.length === tree.expect.length
                && !t.ok
                && rankZeroFirst
                && otherAdded.length === 0
                && removed.length === 0
        }
        if (tree.expect.length === 0) {
            // Every non-lead tree must be byte-identical across arms.
            const identical =
                b.ok === t.ok
                && b.failures.length === t.failures.length
                && b.failures.every((f, i) => f === t.failures[i])
            if (closure.templates.length === 0 && !identical) noTemplateIdentical = false
            if (closure.templates.length > 0 && envAdded.length > 0) declaredSilent = false
            if (tree.label.includes('untracked') && envAdded.length > 0) untrackedInvisible = false
            if (b.ok && !t.ok) noFlipOnClean = false
        }
        if (tree.expect.length > 0 && envAdded.length !== tree.expect.length) {
            // A positive tree that under- or over-fires is a lead-level failure too.
            if (!tree.lead) declaredSilent = declaredSilent && envAdded.length >= tree.expect.length
        }
    }

    const invariants: Invariant[] = [
        {
            label: 'inv-no-template-no-finding',
            ok: noTemplateIdentical,
            detail: 'trees with no tracked template are byte-identical to baseline'
        },
        {
            label: 'inv-declared-silent',
            ok: declaredSilent,
            detail: 'a declared variable never produces a finding'
        },
        {
            label: 'inv-untracked-invisible',
            ok: untrackedInvisible,
            detail: 'gitignored/untracked reads and templates are silent'
        },
        {
            label: 'inv-no-verdict-flip-on-clean',
            ok: noFlipOnClean,
            detail: 'no clean tree flipped PASS → FAIL'
        },
        {label: 'inv-idempotent', ok: idempotent, detail: 'two scans, same findings'},
        {
            label: 'inv-no-suite-flake',
            ok: flakes.length === 0,
            detail:
                flakes.length === 0 ?
                    'no non-env difference between arms'
                :   `${flakes.length} tree(s) differed outside the env lines`
        }
    ]

    const outcome: Outcome =
        templatesSeen === 0 ? 'ABSTAIN'
        : leadPass && invariants.every(i => i.ok) ? 'PASS'
        : 'FAIL'

    const lines = [
        '# A/B-1 — env-template closure (nexttask 10)',
        `baseline ref ${BASELINE_REF}   trees ${CORPUS.length}   carrying a template ${templatesSeen}`,
        '',
        ...rows,
        ...(flakes.length > 0 ?
            ['', '## SUITE FLAKE (non-env differences between arms)', '', ...flakes.map(f => `  ${f}`)]
        :   []),
        '',
        '## invariants',
        '',
        ...invariants.map(i => `  invariant ${i.ok ? 'HOLDS ' : 'BROKEN'} ${i.label} — ${i.detail}`),
        '',
        `${outcome} — the lead ${leadPass ? 'gained both findings at rank 0' : 'did NOT gain both findings at rank 0'}`
            + ` (${((Date.now() - t0) / 1000 / 60).toFixed(1)} min)`,
        `work root ${work}`
    ]
    report({outcome, lines})
}

function slug(s: string): string {
    return s.replace(/[^a-z0-9]+/gi, '-').slice(0, 40)
}

await main()
