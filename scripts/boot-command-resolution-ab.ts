function buildFixture(fx: Fixture, dir: string): void {
    mkdirSync(dir, {recursive: true})
    writeFileSync(path.join(dir, 'package.json'), `${JSON.stringify(fx.pkg, null, 4)}\n`)
    for (const [rel, body] of Object.entries(fx.files ?? {})) {
        writeFileSync(path.join(dir, rel), body)
    }
}

