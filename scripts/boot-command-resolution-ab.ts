/**
 * A/B for nexttask 2 part A — does rejecting NON-LAUNCH scripts stop the gate
 * from resolving its boot command to a container-orchestration script?
 *
 * THE SHAPE (mx5 run 18, measured). `discoverBootCommand` takes `start`, else
 * `dev`. Run 18 has no `start`, and its `dev` is
 *
 *     docker compose -f docker-compose.dev.yml up -d && until docker compose … \
 *       pg_isready …; done && concurrently "bun run dev:css" "bun run dev:js" \
 *       "bun run --watch src/server/index.ts"
 *
 * The gate sandbox has no docker, so the chain died at 127 and the boot SKIPPED as
 * an environment gap — an unfalsifiable outcome, produced for an app that had no
 * HTTP listener anywhere in its source. The command chosen was never a launch of
 * the shipped app in the first place.
 *
 * ARMS. Baseline = `discoverBootCommand` as shipped at BASELINE_REF (extracted with
 * `git show` into a sibling file so its relative imports still resolve); treatment =
 * the working tree. Discovery is a PURE function of the tree, so both arms read the
 * corpus READ-ONLY and no clone is needed for the metric itself.
 *
 * PRE-REGISTERED METRIC, per tree: `(command chosen, boot outcome)`. The target
 * shape is *a tree whose chosen command is infra-orchestration and whose boot
 * outcome is `skip`*. "Infra-orchestration" is judged by a literal regex local to
 * this harness (INFRA_SHAPE_RE below), never by the module under test — a lever may
 * not define its own target shape.
 *
 * BOOT OUTCOMES ARE MEASURED, NOT ASSUMED, and only where they can differ: a tree
 * both arms resolve identically boots identically by construction (same command,
 * same tree), so a boot is executed only for trees where the arms DISAGREE, plus
 * every fixture that exists to prove a real dev script still boots. Real repos boot
 * in a throwaway clone; the corpus is never written to.
 *
 * THE DOCKERLESS SHIM, DISCLOSED. As in scripts/boot-skip-corpus.ts, `docker` and
 * `docker-compose` are shimmed to exit 127 for this process and its children, which
 * reproduces run 18's recorded sandbox exactly. This box DOES have docker, and
 * without the shim the baseline arm's mx5 boot would start real containers on the
 * user's machine — a side effect no measurement justifies. What the shim costs is
 * disclosed rather than hidden: on a docker-HAVING box the baseline chain would get
 * past `up -d` and run the `concurrently` watchers, so mx5's baseline boot outcome
 * there could be `pass`-shaped rather than `skip`. That possibility is exactly what
 * part B settles statically — mx5 has no bind anywhere in its tree, so nothing in
 * that chain can serve — and it is why the invariant below is stated over trees that
 * were OBSERVED to boot rather than over trees that might have.
 *
 * Verdicts (scripts/ab-verdict.ts): PASS exit 0, FAIL exit 1, ABSTAIN exit 2.
 *
 * Run: bun run scripts/boot-command-resolution-ab.ts
 */
