const work = makeWorkRoot('bootcmd')
installDockerlessShim(work)
const results: TreeResult[] = []

/** Real trees: pi-task plus every sibling checkout under ~/hub — the corpus widens
 *  with the box rather than being pinned to whatever existed when this was written. */
function realTrees(): Array<{label: string; dir: string}> {
    const out = [{label: 'pi-task (self)', dir: REPO}]
    if (existsSync(HUB)) {
        for (const name of readdirSync(HUB).sort()) {
            const dir = path.join(HUB, name)
            if (existsSync(path.join(dir, 'package.json')) || existsSync(path.join(dir, 'Makefile'))) {
                out.push({label: name, dir})
            }
        }
    }
    return out
}

/** A throwaway clone, so a boot that writes (build caches, logs) cannot touch the
 *  corpus. CoW where the filesystem allows, as in boot-skip-corpus. */
function clone(src: string, dest: string): string {
    rmSync(dest, {recursive: true, force: true})
    const cp = spawnSync('cp', ['-a', '--reflink=auto', src, dest], {encoding: 'utf8'})
    if (cp.status !== 0) throw new Error(`cp failed for ${src}: ${cp.stderr}`)
    return dest
}

async function runReal(
    entry: {label: string; dir: string},
    baselineDiscover: DiscoverFn
): Promise<void> {
    const baseCmd = baselineDiscover(entry.dir)
    const treatCmd = discoverBootCommand(entry.dir)
    const differs = label(baseCmd) !== label(treatCmd)
    let baselineBoot: BootClass | '' = ''
    let treatmentBoot: BootClass | '' = ''
    if (differs) {
        // Only here can the two arms produce different runtime behaviour, so this is
        // the only place a boot has to be spent.
        const dir = clone(entry.dir, path.join(work, `${entry.label.replace(/\W+/g, '_')}.boot`))
        try {
            baselineBoot = await bootOutcome(dir, baseCmd)
            treatmentBoot = await bootOutcome(dir, treatCmd)
        } finally {
            rmSync(dir, {recursive: true, force: true})
        }
    }
    results.push({
        label: entry.label,
        dir: entry.dir,
        baselineCmd: label(baseCmd),
        treatmentCmd: label(treatCmd),
        baselineBody: bodyOf(entry.dir, baseCmd),
        baselineBoot,
        treatmentBoot,
        realDevFixture: false
    })
}

async function runFixture(fx: Fixture, baselineDiscover: DiscoverFn): Promise<void> {
    const dir = path.join(work, fx.key)
    buildFixture(fx, dir)
    const baseCmd = baselineDiscover(dir)
    const treatCmd = discoverBootCommand(dir)
    const differs = label(baseCmd) !== label(treatCmd)
    const measure = fx.measureBoot === true || differs
    results.push({
        label: `fixture:${fx.key}`,
        dir,
        baselineCmd: label(baseCmd),
        treatmentCmd: label(treatCmd),
        baselineBody: bodyOf(dir, baseCmd),
        baselineBoot: measure ? await bootOutcome(dir, baseCmd) : '',
        treatmentBoot: measure ? await bootOutcome(dir, treatCmd) : '',
        realDevFixture: fx.realDev === true
    })
}

const isInfra = (t: TreeResult): boolean => INFRA_SHAPE_RE.test(t.baselineBody.trim())
/** The target shape, in the arm's own terms: an infra-orchestration command chosen,
 *  and a boot that observed nothing. */
const targetBaseline = (t: TreeResult): boolean => isInfra(t) && t.baselineBoot === 'skip'
const targetTreatment = (t: TreeResult): boolean =>
    INFRA_SHAPE_RE.test(bodyOfTreatment(t).trim()) && t.treatmentBoot === 'skip'

function bodyOfTreatment(t: TreeResult): string {
    if (t.treatmentCmd === 'none') return ''
    const name = t.treatmentCmd.split(' ')[2] ?? ''
    return scriptsOf(t.dir)[name] ?? ''
}

