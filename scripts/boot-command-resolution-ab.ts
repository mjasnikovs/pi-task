/** v0.24.5 — the last release before the non-launch rejection. PINNED, not HEAD:
 *  once the lever lands, HEAD contains it and the A/B would compare it to itself. */
const BASELINE_REF = process.env.BOOT_CMD_BASELINE_REF ?? '1e15b8b'
const BASELINE_FILE = path.join(REPO, 'src', 'task', 'final-gate.bootcmd-baseline.gen.ts')

type DiscoverFn = (cwd: string) => HealthCommand | null

async function loadBaselineDiscover(): Promise<DiscoverFn> {
    const show = spawnSync('git', ['show', `${BASELINE_REF}:src/task/final-gate.ts`], {
        cwd: REPO,
        encoding: 'utf8',
        maxBuffer: 32 * 1024 * 1024
    })
    if (show.status !== 0 || !show.stdout) {
        throw new Error(`cannot read final-gate.ts at ${BASELINE_REF}: ${show.stderr}`)
    }
    writeFileSync(
        BASELINE_FILE,
        `// GENERATED by scripts/boot-command-resolution-ab.ts from ${BASELINE_REF} — do not edit, do not commit.\n`
            + show.stdout
    )
    const mod: unknown = await import(BASELINE_FILE)
    rmSync(BASELINE_FILE, {force: true})
    return (mod as {discoverBootCommand: DiscoverFn}).discoverBootCommand
}

/**
 * The harness's OWN definition of an infra-orchestration script body: the first
 * member of the chain invokes a container tool and hands it an `up`/`start` verb.
 * Deliberately independent of nonLaunchScriptReason — the metric must not be
 * whatever the treatment happens to reject.
 */
const INFRA_SHAPE_RE = /^[^&|;]*\b(?:docker|podman|nerdctl)(?:[-\s]compose)?\b[^&|;]*\b(?:up|start)\b/

function scriptsOf(dir: string): Record<string, string> {
    try {
        const j = JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8')) as {
            scripts?: Record<string, string>
        }
        return j.scripts ?? {}
    } catch {
        return {}
    }
}

/** The script BODY behind a chosen `bun run <name>`, or '' for make/none. */
function bodyOf(dir: string, cmd: HealthCommand | null): string {
    if (!cmd || cmd[0] !== 'bun' || cmd[1][0] !== 'run') return ''
    return scriptsOf(dir)[cmd[1][1]] ?? ''
}

const label = (cmd: HealthCommand | null): string => (cmd ? `${cmd[0]} ${cmd[1].join(' ')}` : 'none')

type BootClass = 'none' | 'pass' | 'fail' | 'skip' | 'orphan-port'

interface TreeResult {
    label: string
    dir: string
    baselineCmd: string
    treatmentCmd: string
    baselineBody: string
    /** Measured, or 'none' when there was no command; '' when not measured. */
    baselineBoot: BootClass | ''
    treatmentBoot: BootClass | ''
    /** A fixture whose dev script is a plain server launch (inv-real-dev-kept). */
    realDevFixture: boolean
}

async function bootOutcome(dir: string, cmd: HealthCommand | null): Promise<BootClass> {
    if (!cmd) return 'none'
    const expectServer = detectsServedApp(dir)
    const r = await runBootCheck(dir, cmd, 8_000, {
        expectServer,
        // The render probes are deliberately NOT injected: this A/B measures which
        // command is chosen and whether it comes up, not what the page looks like.
        deps: {preferredPort: () => preferredDeclaredPort(dir)}
    })
    return r.outcome
}

